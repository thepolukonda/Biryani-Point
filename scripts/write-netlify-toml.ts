/**
 * npm run netlify:toml
 * Writes netlify.toml from security-headers.ts (a unit test checks they match).
 */
import fs from 'node:fs';
import path from 'node:path';
import { securityHeaders } from '../security-headers';

const q = (s: string) => JSON.stringify(s);
const headers = securityHeaders()
  .map((h) => `    ${h.key} = ${q(h.value)}`)
  .join('\n');

const toml = `# Netlify configuration. Generated by \`npm run netlify:toml\` from security-headers.ts.
# Netlify detects Next.js and uses its official adapter automatically (free plan is fine).

[build]
  command = "npm run build"
  publish = ".next"

[build.environment]
  NODE_VERSION = "22"
  NEXT_TELEMETRY_DISABLED = "1"

# The Google Sheet import runs every 5 minutes (netlify/functions/sheet-sync.mts).
[functions]
  directory = "netlify/functions"

[[headers]]
  for = "/*"
  [headers.values]
${headers}

[[headers]]
  for = "/sw.js"
  [headers.values]
    Cache-Control = "no-cache"
`;

fs.writeFileSync(path.join(__dirname, '..', 'netlify.toml'), toml);
console.log('Wrote netlify.toml');
