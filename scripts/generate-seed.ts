/**
 * npm run seed:generate
 *
 * 1. Writes the starting Google Sheet: docs/sheet-template/biryani-point-menu.xlsx (+ one CSV per tab).
 * 2. Runs those CSVs through the real Sheet importer and writes supabase/seed.sql,
 *    so the local database starts with exactly what the template would import.
 */
import fs from 'node:fs';
import path from 'node:path';
import ExcelJS from 'exceljs';
import { buildSnapshot } from '../src/model-helpers/sheet/build';
import { templateTabs, toCsv } from './sheet-template-data';

const root = path.join(__dirname, '..');
const templateDir = path.join(root, 'docs', 'sheet-template');

// Local development login (only created by `supabase db reset` on your machine).
