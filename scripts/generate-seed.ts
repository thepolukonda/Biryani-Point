const DEV_STAFF_PASSWORD = 'bp-local-kitchen-2026';

async function writeTemplate() {
  fs.mkdirSync(templateDir, { recursive: true });
  const tabs = templateTabs();
  const csv: Record<string, string> = {};

  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'Biryani Point';
  for (const tab of tabs) {
    csv[tab.name.toLowerCase()] = toCsv(tab);
    fs.writeFileSync(
      path.join(templateDir, `${tab.name.toLowerCase()}.csv`),
      csv[tab.name.toLowerCase()]!,
    );

    const sheet = workbook.addWorksheet(tab.name, { views: [{ state: 'frozen', ySplit: 1 }] });
    sheet.addRow(tab.header);
    for (const row of tab.rows) sheet.addRow(row);
    sheet.getRow(1).font = { bold: true, color: { argb: 'FF1A1208' } };
    sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE9A72D' } };
    tab.widths?.forEach((w, i) => (sheet.getColumn(i + 1).width = w));
    sheet.eachRow((row) => (row.alignment = { vertical: 'top', wrapText: true }));
    // Prices and times as text, so Sheets never turns 12:00 into a date or 22.50 into 22.5.
    sheet.eachRow((row, n) => {
      if (n > 1) row.eachCell((c) => (c.numFmt = '@'));
    });
  }
  await workbook.xlsx.writeFile(path.join(templateDir, 'biryani-point-menu.xlsx'));
  return csv;
}

function sqlString(value: string) {
  return `'${value.replace(/'/g, "''")}'`;
}

function devUserSql(
  id: string,
  email: string,
  password: string,
  role: 'owner' | 'staff',
  name: string,
) {
  return `
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change, email_change_token_new)
values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated',
  ${sqlString(email)}, extensions.crypt(${sqlString(password)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');

insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), '${id}', '${id}',
  jsonb_build_object('sub', '${id}', 'email', ${sqlString(email)}, 'email_verified', true),
  'email', now(), now(), now());

insert into public.staff (user_id, role, display_name) values ('${id}', '${role}', ${sqlString(name)});
`;
}

async function main() {
  const csv = await writeTemplate();
  const result = buildSnapshot(
    {
      menu: csv.menu!,
      categories: csv.categories,
      options: csv.options,
      hours: csv.hours,
      settings: csv.settings,
    },
    [],
  );
  for (const p of result.problems)
    console.warn(`[${p.severity}] ${p.tab}${p.row ? ` row ${p.row}` : ''}: ${p.message}`);
  if (!result.ok) throw new Error('The template does not import cleanly; see problems above.');
  if (result.problems.some((p) => p.severity === 'error'))
    throw new Error('The template has errors.');

  const sql = `-- Generated by \`npm run seed:generate\` from scripts/prototype-data.json. Do not edit by hand.
-- Local development only: \`supabase db reset\` runs this file. It is never run on the live project.

-- Menu, options, hours and settings: the same import the Google Sheet uses.
select public.apply_menu_snapshot(${sqlString(JSON.stringify(result.snapshot))}::jsonb);

-- No Google Sheet is connected yet, so hours and settings stay editable in Admin -> Settings.
-- (Once a Sheet is connected, whatever its Hours/Settings tabs contain takes over.)
update public.opening_hours set source = 'admin';
update public.restaurant_settings set sheet_managed_fields = '{}' where id = 1;

-- Placeholder delivery area: 5 km around the restaurant, using the default fee.
-- TODO(owner): set the real delivery area in Admin -> Settings -> Delivery zones.
insert into public.delivery_zones (name, kind, radius_km, sort_order)
values ('Batumi (5 km)', 'radius', 5, 0);

-- Local login for the admin panel (see README "Local development").
${devUserSql('11111111-1111-4111-8111-111111111111', DEV_OWNER_EMAIL, DEV_OWNER_PASSWORD, 'owner', 'Owner (local)')}
${devUserSql('22222222-2222-4222-8222-222222222222', DEV_STAFF_EMAIL, DEV_STAFF_PASSWORD, 'staff', 'Kitchen (local)')}
`;
  fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), sql);
  console.log(
    `Wrote supabase/seed.sql (${result.snapshot.items.length} dishes, ${result.snapshot.categories.length} categories) and docs/sheet-template/`,
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
